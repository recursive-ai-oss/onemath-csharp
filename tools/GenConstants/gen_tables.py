#!/usr/bin/env python3
"""Generates src/OneMath/Functions/FastTables.cs: the lookup tables of the fast evaluation stage.

All values are computed with mpmath at 600 bits and written as double-doubles (hi, lo) in shortest round-trip decimal form,
which the C# compiler parses exactly, so no platform function decides a table entry.

    python3 gen_tables.py > ../../src/OneMath/Functions/FastTables.cs
"""
from mpmath import mp, mpf, pi, log, exp, sin, cos, atan, floor, ldexp

mp.prec = 600


def dd(v):
    hi = float(v)
    lo = float(v - mpf(hi))
    return hi, lo


def arr(name, vals, doc):
    print('    /// <summary>%s</summary>' % doc)
    print('    internal static readonly double[] %s =' % name)
    print('    [')
    line = '       '
    for v in vals:
        s = ' %r,' % v
        if len(line) + len(s) > 118:
            print(line)
            line = '       '
        line += s
    print(line)
    print('    ];')


def round_to_bits(v, nbits):
    e = int(floor(mp.log(abs(v), 2)))
    scale = nbits - 1 - e
    m = mp.nint(ldexp(v, scale))
    r = ldexp(m, -scale)
    return float(r), r


print('// <auto-generated> by tools/GenConstants/gen_tables.py; do not edit. </auto-generated>')
print('namespace RecursiveAI.OneMath;')
print()
print('/// <summary>Lookup tables for the fast stage (double-double entries as separate hi and lo arrays).</summary>')
print('internal static class FastTables')
print('{')

# exp: 2^(j/64)
hi, lo = zip(*[dd(mpf(2) ** (mpf(j) / 64)) for j in range(64)])
arr('ExpHi', hi, '2^(j/64), high part, j = 0..63.')
arr('ExpLo', lo, '2^(j/64), low part.')

# log: for the mantissa interval j of 128 equal parts of [1, 2), inv = 1/centre rounded to double; L = -log(inv)
invs = []
lh = []
ll = []
for j in range(128):
    c = 1 + (mpf(j) + mpf(1) / 2) / 128
    inv = float(1 / c)
    invs.append(inv)
    h, l = dd(-log(mpf(inv)))
    lh.append(h)
    ll.append(l)
arr('LogInv', invs, 'Reciprocal of the centre of mantissa interval j (of 128 in [1, 2)), as a double.')
arr('LogHi', lh, '-log(LogInv[j]), high part.')
arr('LogLo', ll, '-log(LogInv[j]), low part.')

# sin and cos of j/128, j = 0..101 (j/128 <= pi/4 + 1/128)
N = 102
sh, sl = zip(*[dd(sin(mpf(j) / 128)) for j in range(N)])
ch, cl = zip(*[dd(cos(mpf(j) / 128)) for j in range(N)])
arr('SinHi', sh, 'sin(j/128), high part, j = 0..101.')
arr('SinLo', sl, 'sin(j/128), low part.')
arr('CosHi', ch, 'cos(j/128), high part.')
arr('CosLo', cl, 'cos(j/128), low part.')

# atan(j/64), j = 0..64
ah, al = zip(*[dd(atan(mpf(j) / 64)) for j in range(65)])
arr('AtanHi', ah, 'atan(j/64), high part, j = 0..64.')
arr('AtanLo', al, 'atan(j/64), low part.')

# pi/2 for Cody-Waite reduction: three 33-bit parts and a full double remainder.
rem = pi / 2
parts = []
for nb in (33, 33, 33):
    d, ex = round_to_bits(rem, nb)
    parts.append(d)
    rem = rem - ex
parts.append(float(rem))
for i, p in enumerate(parts):
    print('    /// <summary>Part %d of pi/2 (parts 1-3 have 33 significant bits, so k * part is exact for |k| &lt; 2^20).</summary>' % (i + 1))
    print('    internal const double PiO2Part%d = %r;' % (i + 1, p))
# ln(2)/64 in parts for the exp reduction: two 34-bit parts (n * part exact for |n| < 2^19) and a full double.
rem = log(mpf(2)) / 64
parts = []
for nb in (34, 34):
    d, ex = round_to_bits(rem, nb)
    parts.append(d)
    rem = rem - ex
parts.append(float(rem))
for i, p in enumerate(parts):
    print('    /// <summary>Part %d of ln(2)/64 (parts 1 and 2 have 34 significant bits).</summary>' % (i + 1))
    print('    internal const double Ln2By64Part%d = %r;' % (i + 1, p))
print('}')
