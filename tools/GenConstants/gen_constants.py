#!/usr/bin/env python3
"""Generates src/OneMath/Functions/Constants.cs (fixed constants as exact bit patterns).

Uses mpmath at 1600 bits as an independent source of pi, ln 2 and ln 10. Run:
    python3 gen_constants.py > ../../src/OneMath/Functions/Constants.cs
"""
import struct
from mpmath import mp, mpf, pi, log, floor, ldexp

mp.prec = 1700


def bits(d):
    return struct.unpack('<Q', struct.pack('<d', d))[0]


def round_to_bits(v, nbits):
    """Round v to a double holding at most nbits significant bits (round to nearest)."""
    if v == 0:
        return 0.0, mpf(0)
    e = int(mp.floor(mp.log(abs(v), 2)))
    scale = nbits - 1 - e
    m = mp.nint(ldexp(v, scale))
    r = ldexp(m, -scale)
    return float(r), r


def split(v, parts):
    """Splits v into doubles with the given significant-bit budgets; the last takes 53."""
    out = []
    rem = v
    for nb in parts:
        d, exact = round_to_bits(rem, nb)
        out.append(d)
        rem = rem - exact
    return out


def dd(v):
    return split(v, [53, 53])


def lit(d):
    return 'BitConverter.Int64BitsToDouble(unchecked((long)0x%016XUL))' % bits(d)


def ddlit(name, v, doc):
    h, l = dd(v)
    print('    /// <summary>%s</summary>' % doc)
    print('    internal static readonly DD %s = new(%s,\n        %s);' % (name, lit(h), lit(l)))


ln2 = log(2)
ln10 = log(10)
print('// <auto-generated> by tools/GenConstants/gen_constants.py; do not edit. </auto-generated>')
print('using System;')
print()
print('namespace RecursiveAI.OneMath;')
print()
print('/// <summary>Fixed constants as exact IEEE bit patterns, so no platform conversion decides a bit.</summary>')
print('internal static class Consts')
print('{')
ddlit('Ln2', ln2, 'ln 2 as a double-double.')
ddlit('Ln10', ln10, 'ln 10 as a double-double.')
ddlit('InvLn2', 1 / ln2, '1 / ln 2 as a double-double.')
ddlit('InvLn10', 1 / ln10, '1 / ln 10 as a double-double.')
ddlit('Pi', pi, 'pi as a double-double.')
ddlit('PiOver2', pi / 2, 'pi / 2 as a double-double.')
l = split(ln2, [40, 40, 53])
for i, d in enumerate(l):
    print('    /// <summary>Part %d of ln 2 (parts 1 and 2 have 40 significant bits so k * part is exact for |k| &lt; 2^12).</summary>' % (i + 1))
    print('    internal static readonly double Ln2Part%d = %s;' % (i + 1, lit(d)))
# 2/pi fraction words, big-endian, 64 bits each.
w = 2 / pi
words = []
for i in range(24):
    w = w * (mpf(2) ** 64)
    f = int(mp.floor(w))
    words.append(f)
    w = w - f
print('    /// <summary>Binary expansion of 2/pi, 64 bits per word, most significant first (Payne-Hanek reduction).</summary>')
print('    internal static readonly ulong[] TwoOverPi =')
print('    [')
for f in words:
    print('        0x%016XUL,' % f)
print('    ];')
print('}')
